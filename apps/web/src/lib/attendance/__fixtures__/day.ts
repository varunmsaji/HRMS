/** A day on which the employee never punched (zero-punch ABSENT). */
export function makeAbsentDay(overrides: Partial<AttendanceDay> = {}): AttendanceDay {
  return makeDay({
    attendance_status: "ABSENT",
    actual_first_in: null,
    actual_last_out: null,
    worked_minutes: 0,
    ...overrides,
  });
}
